"""Generate deterministic Stage A targets, rules, isolated fixtures and Grafana JSON."""
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
APIS = ("user-service", "product-service", "inventory-service", "order-service", "payment-service", "notification-service")
COMPONENTS = ("gateway", "frontend", *APIS)
NAMES = {"gateway": "Gateway", "frontend": "Frontend", "user-service": "Usuarios", "product-service": "Catálogo",
         "inventory-service": "Inventario", "order-service": "Pedidos", "payment-service": "Pagos", "notification-service": "Notificaciones"}
SOURCE = {"type": "prometheus", "uid": "uce-prometheus"}
STATE_MAPPINGS = [{"type": "value", "options": {str(value): {"text": text, "color": color, "index": value}
                   for value, text, color in ((0, "UNKNOWN", "#748399"), (1, "DOWN", "#b83d49"),
                                               (2, "DEGRADED", "#bf870d"), (3, "UP", "#23866c"))}},
                  {"type": "special", "options": {"match": "null", "result": {"text": "UNKNOWN", "color": "#748399", "index": 4}}}]


def targets():
    rows = []
    for component in APIS:
        for probe in ("live", "ready"):
            rows.append({"targets": [f"http://{component}:8000/health/{probe}"],
                         "labels": {"component": component, "probe": probe, "module": probe}})
    rows.extend([
        {"targets": ["http://gateway/health"], "labels": {"component": "gateway", "probe": "edge", "module": "live"}},
        {"targets": ["http://frontend:8080/healthz"], "labels": {"component": "frontend", "probe": "edge", "module": "frontend"}},
        {"targets": ["http://gateway/"], "labels": {"component": "frontend", "probe": "route", "module": "frontend_route"}},
    ])
    return rows


def rules():
    rows = [{"record": "uce:component_expected", "expr": "vector(1)", "labels": {"component": c}} for c in COMPONENTS]
    rows += [
        {"record": "uce:probe_success:fresh", "expr": '''probe_success{job="blackbox"}
and on(job, instance) (up{job="blackbox"} == 1)
and on(job, instance) ((time() - timestamp(probe_success{job="blackbox"})) <= 25)
and on(job, instance) ((time() - timestamp(up{job="blackbox"})) <= 25)'''},
        {"record": "uce:live", "expr": 'max by(component) (uce:probe_success:fresh{probe="live"})'},
        {"record": "uce:ready", "expr": 'max by(component) (uce:probe_success:fresh{probe="ready"})'},
        {"record": "uce:edge", "expr": 'max by(component) (uce:probe_success:fresh{probe="edge"})'},
        # Expected components only provide UNKNOWN, never a synthetic UP or latency.
        {"record": "uce:component_state", "expr": '''(3 * ((uce:live == 1) and on(component) (uce:ready == 1)))
or on(component) (2 * ((uce:live == 1) and on(component) (uce:ready == 0)))
or on(component) ((uce:live == 0) + 1)
or on(component) (3 * (uce:edge == 1))
or on(component) ((uce:edge == 0) + 1)
or on(component) (0 * uce:component_expected)'''},
        {"record": "uce:frontend_route_state", "expr": '''(3 * (max(uce:probe_success:fresh{probe="route"}) == 1))
or ((2 + (max(uce:probe_success:fresh{probe="route"}) == 0))
and (max(uce:probe_success:fresh{component="gateway", probe="edge"}) == 1))
or vector(0)'''},
        # Count only adjacent, known transitions. UNKNOWN and collection gaps are not incidents.
        {"record": "uce:down_transition", "expr": '''((uce:component_state == bool 1)
* on(component) (uce:component_state offset 5s > bool 1)
and on(component) ((time() - timestamp(uce:component_state offset 5s)) <= 15))
or on(component) (0 * uce:component_expected)'''},
        {"record": "uce:recovery_transition", "expr": '''((uce:component_state == bool 3)
* on(component) (uce:component_state offset 5s > bool 0)
* on(component) (uce:component_state offset 5s < bool 3)
and on(component) ((time() - timestamp(uce:component_state offset 5s)) <= 15))
or on(component) (0 * uce:component_expected)'''},
    ]
    return rows


def rules_yaml():
    lines = ["# Generated by generate_dashboard.py; edit its rules() and regenerate.", "groups:",
             "  - name: uce_stage_a", "    interval: 5s", "    rules:"]
    for rule in rules():
        lines += ["      - record: " + rule["record"], "        expr: |"]
        lines += ["          " + line for line in rule["expr"].splitlines()]
        if "labels" in rule:
            lines += ["        labels:"] + [f"          {key}: {value}" for key, value in rule["labels"].items()]
    return "\n".join(lines) + "\n"


def rule_tests():
    cases = []
    def series(live, ready, up="1+0x12"):
        result = []
        for probe, values in (("live", live), ("ready", ready)):
            labels = f'job="blackbox",component="user-service",probe="{probe}",instance="http://user-service:8000/health/{probe}"'
            if values is not None:
                result += [{"series": "probe_success{" + labels + "}", "values": values},
                           {"series": "up{" + labels + "}", "values": up}]
        return result
    def case(name, inputs, time, expected, extra=()):
        cases.append({"name": name, "interval": "5s", "input_series": inputs,
                      "promql_expr_test": [{"expr": 'uce:component_state{component="user-service"}', "eval_time": time,
                                            "exp_samples": [{"labels": 'uce:component_state{component="user-service"}', "value": expected}]}, *extra]})
    case("both checks pass", series("1+0x12", "1+0x12"), "30s", 3)
    case("ready fails while live passes", series("1+0x12", "0+0x12"), "30s", 2)
    case("live fails", series("0+0x12", "0+0x12"), "30s", 1)
    case("no samples is UNKNOWN", [], "30s", 0)
    case("missing ready is UNKNOWN", series("1+0x12", None), "30s", 0)
    case("exporter failure is UNKNOWN", series("1+0x12", "1+0x12", "0+0x12"), "30s", 0)
    case("old samples are UNKNOWN before lookback expires", series("1", "1", "1"), "40s", 0)
    def counter_test(metric, value):
        return {"expr": f'sum_over_time({metric}{{component="user-service"}}[40s])', "eval_time": "40s",
                "exp_samples": [{"labels": '{component="user-service"}', "value": value}]}
    case("one confirmed fall and recovery", series("1 1 1 0 0 1 1 1 1", "1+0x12"), "40s", 3,
         [counter_test("uce:down_transition", 1), counter_test("uce:recovery_transition", 1)])
    case("unknown gap does not fabricate recovery", series("1+0x12", "1+0x12", "1 1 0 0 1 1 1 1 1"), "40s", 3,
         [counter_test("uce:down_transition", 0), counter_test("uce:recovery_transition", 0)])
    for name, gateway, route, expected_state in (("frontend route available", 1, 1, 3),
                                                 ("frontend route degraded with gateway up", 1, 0, 2),
                                                 ("gateway outage does not blame frontend route", 0, 0, 0)):
        inputs = []
        for component, probe, value in (("gateway", "edge", gateway), ("frontend", "edge", 1), ("frontend", "route", route)):
            labels = f'job="blackbox",component="{component}",probe="{probe}",instance="http://{component}/{probe}"'
            inputs += [{"series": "probe_success{" + labels + "}", "values": f"{value}+0x12"},
                       {"series": "up{" + labels + "}", "values": "1+0x12"}]
        cases.append({"name": name, "interval": "5s", "input_series": inputs, "promql_expr_test": [
            {"expr": "uce:frontend_route_state", "eval_time": "30s",
             "exp_samples": [{"labels": "uce:frontend_route_state", "value": expected_state}]},
            {"expr": 'uce:component_state{component="frontend"}', "eval_time": "30s",
             "exp_samples": [{"labels": 'uce:component_state{component="frontend"}', "value": 3}]}]})
    return {"rule_files": ["rules.yml"], "evaluation_interval": "5s", "tests": cases}


def query(expression, ref="A", instant=False, legend="{{component}}", table=False):
    return {"refId": ref, "datasource": SOURCE, "expr": expression, "instant": instant, "range": not instant,
            "format": "table" if table else "time_series", "legendFormat": legend, "editorMode": "code"}


def panel(pid, title, kind, x, y, w, h, expression=None, options=None, defaults=None, description=""):
    result = {"id": pid, "title": title, "type": kind, "gridPos": {"x": x, "y": y, "w": w, "h": h},
              "datasource": SOURCE, "description": description, "options": options or {},
              "fieldConfig": {"defaults": defaults or {}, "overrides": []}}
    if expression:
        result["targets"] = [query(expression, instant=kind in ("stat", "table"), table=kind == "table")]
    return result


