def generated_files():
    dump = lambda value: json.dumps(value, ensure_ascii=False, indent=2) + "\n"
    return {"targets.json": dump(targets()), "rules.yml": rules_yaml(),
            "rules.test.yml": "# Isolated fixtures only; never loaded by the running Prometheus.\n" + dump(rule_tests()),
            "grafana/dashboards/uce-observability.json": dump(dashboard())}


def main():
    for name, content in generated_files().items():
        path = HERE / name
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8", newline="\n")
    print("Generated Stage A configuration inside tests/demo/observability")


if __name__ == "__main__":
    main()
