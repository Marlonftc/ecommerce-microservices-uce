"""Stage 6: the React application behind the gateway.

- Routes of the application reloaded directly answer index.html (no 404).
- Hashed assets are cached for a year; a missing asset is a real 404.
- The security headers and X-Request-ID are present on HTML, assets, API
  responses and errors generated by nginx.
- Only GET and HEAD reach the frontend.
- The normal image is built with VITE_PAYMENT_DEMO=false.
- The API keeps working with the frontend stopped and after restarting the gateway.
"""
import re

import pytest

from support import (NOT_FOUND, compose, containers, gw, inspect, log_entry, rid, run, wait_healthy,
                     wait_until)

CSP = ("default-src 'self'; script-src 'self'; style-src 'self'; img-src 'self'; font-src 'self'; "
       "connect-src 'self'; object-src 'none'; base-uri 'none'; form-action 'self'; frame-ancestors 'none'")
SECURITY = {
    "content-security-policy": CSP,
    "x-content-type-options": "nosniff",
    "x-frame-options": "DENY",
    "referrer-policy": "same-origin",
    "permissions-policy": "camera=(), microphone=(), geolocation=(), payment=()",
    "cross-origin-opener-policy": "same-origin",
    "cross-origin-resource-policy": "same-origin",
}
UNAVAILABLE = {"detail": {"code": "UPSTREAM_UNAVAILABLE", "message": "The service is not available"}}
SPA_ROUTES = ["/", "/login", "/registro", "/productos", "/carrito", "/pedidos", "/pedidos/abc",
              "/notificaciones", "/admin", "/admin/productos", "/admin/usuarios", "/admin/operaciones",
              "/ruta-que-no-existe"]


def assert_security_headers(response, label: str) -> None:
    for name, value in SECURITY.items():
        assert response.headers.get(name) == value, (label, name, response.headers.get(name))
        # one copy only: the frontend adds none of them
        assert len(response.headers.get_list(name)) == 1, (label, name)
    assert re.fullmatch(r"[A-Za-z0-9-]{8,64}", response.headers["x-request-id"]), label


def bundle_paths(c) -> tuple[str, str]:
    html = c.get("/").text
    js = re.search(r'src="(/assets/index-[A-Za-z0-9_-]+\.js)"', html).group(1)
    css = re.search(r'href="(/assets/index-[A-Za-z0-9_-]+\.css)"', html).group(1)
    return js, css


def test_spa_routes_reload_without_404():
    with gw() as c:
        for path in SPA_ROUTES:
            r = c.get(path)
            assert r.status_code == 200, path
            assert r.headers["content-type"].startswith("text/html"), path
            assert r.headers["cache-control"] == "no-cache", path
            assert '<div id="root"></div>' in r.text, path


def test_index_html_has_no_inline_code():
    # What makes the strict CSP possible: only external files of the same origin
    with gw() as c:
        html = c.get("/").text
    assert not re.search(r"<script(?![^>]*\bsrc=)[^>]*>", html), "inline script"
    assert "<style" not in html and "style=" not in html and "data:" not in html
    assert not re.search(r'(src|href)="(https?:)?//', html), "external origin"


def test_assets_cache_and_missing_files():
    with gw() as c:
        js, css = bundle_paths(c)
        for path, kind in [(js, "javascript"), (css, "text/css")]:
            r = c.get(path)
            assert r.status_code == 200 and kind in r.headers["content-type"], path
            assert r.headers["cache-control"] == "public, max-age=31536000, immutable", path
        # A missing asset is never answered with index.html (HTML served as JavaScript)
        missing = c.get("/assets/index-doesnotexist.js")
        assert missing.status_code == 404 and '<div id="root">' not in missing.text
        assert c.get("/favicon.svg").headers["content-type"].startswith("image/svg+xml")


def test_security_headers_on_every_kind_of_response(adm):
    with gw() as c:
        js, _ = bundle_paths(c)
        own = rid("html")
        html = c.get("/login", headers={"X-Request-ID": own})
        assert html.headers["x-request-id"] == own
        assert log_entry(own)["upstream_addr"] != ""          # reached the frontend
        cases = {
            "html": html,
            "asset": c.get(js),
            "api 200": c.get("/api/products", params={"limit": 1}),
            "api 401": c.get("/api/users/me"),
            "api 404 (nginx)": c.get("/api/does-not-exist"),
            "internal 404": c.get("/internal/products/1"),
            "missing asset 404": c.get("/assets/missing.js"),
            "405": c.post("/login", json={}),
            "413": c.post("/api/products", headers={**adm.headers, "Content-Type": "application/json"},
                          content=b"x" * (1024 * 1024 + 1)),
        }
    for label, response in cases.items():
        assert_security_headers(response, label)
    assert cases["api 404 (nginx)"].json() == NOT_FOUND
    assert cases["internal 404"].json() == NOT_FOUND
    assert cases["413"].status_code == 413


def test_only_get_and_head_reach_the_frontend():
    with gw() as c:
        assert c.head("/carrito").status_code == 200
        for method in ["POST", "PUT", "PATCH", "DELETE", "OPTIONS"]:
            request_id = rid(method.lower())
            r = c.request(method, "/carrito", headers={"X-Request-ID": request_id})
            assert r.status_code == 405, method
            assert r.json() == {"detail": {"code": "METHOD_NOT_ALLOWED", "message": "Method not allowed"}}
            assert log_entry(request_id)["upstream_addr"] == "", method     # nothing forwarded


def test_normal_image_is_built_without_payment_demo():
    container = inspect(containers("frontend")[0]["Name"])
    image = container["Config"]["Image"]
    if image.endswith(":e2e"):
        pytest.skip("the E2E frontend is running; restore the normal one first (see README)")
    labels = container["Config"]["Labels"] or {}
    assert labels.get("uce.payment-demo") == "false", labels.get("uce.payment-demo")
    # And the bundle really served by the gateway does not contain the demo options
    with gw() as c:
        js, _ = bundle_paths(c)
        assert "Opciones de demostración" not in c.get(js).text


@pytest.mark.docker
def test_api_works_with_the_frontend_stopped_and_after_a_gateway_restart(customer):
    compose("stop", "frontend")
    try:
        with gw() as c:
            # Until nginx drops the old address a connect timeout (504) is possible
            def unavailable():
                r = c.get("/carrito")
                assert r.status_code in (502, 504), r.status_code
                return r if r.status_code == 502 else None

            r = wait_until(unavailable, 40, interval=1, what="502 for the stopped frontend")
            assert r.json() == UNAVAILABLE
            assert_security_headers(r, "502 frontend stopped")
            assert c.get("/api/products", params={"limit": 1}).status_code == 200
            assert c.get("/api/users/me", headers=customer.headers).json()["id"] == customer.id
            assert c.get("/api/does-not-exist").json() == NOT_FOUND

        # The gateway starts without the frontend (no depends_on, names resolved at runtime)
        compose("restart", "gateway")
        wait_healthy("gateway", timeout=60)
        with gw() as c:
            wait_until(lambda: c.get("/api/products", params={"limit": 1}).status_code == 200, 30,
                       interval=1, what="the API after the gateway restart")
            assert c.get("/api/users/me", headers=customer.headers).status_code == 200
            assert c.get("/").status_code == 502
    finally:
        compose("start", "frontend")
        wait_healthy("frontend", timeout=60)
    with gw() as c:
        wait_until(lambda: c.get("/carrito").status_code == 200, 40, interval=1,
                   what="the frontend back through the gateway")
    run("docker", "image", "inspect", "ecommerce-uce/frontend")       # the image still exists
